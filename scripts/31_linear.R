data(cars)
print(head(cars,10))
print(tail(cars,10))
str(cars)
summary(cars)
dim(cars)
plot(cars$speed,cars$dist,main="Speed vs Stopping Distance",xlab="Speed (mph)",ylab="Stopping Distance")
model<-lm(dist~speed,data=cars)
print(summary(model))
prediction<-predict(model,data.frame(speed=20))
print(prediction)
plot(cars$speed,cars$dist,main="Simple Linear Regression",xlab="Speed (mph)",ylab="Stopping Distance")
abline(model)
print(coef(model))
print(summary(model)$r.squared)
cat("Regression Equation: dist =",round(coef(model)[1],2),"+",round(coef(model)[2],2),"* speed\n")
cat("At 20 mph, predicted stopping distance =",round(prediction,2),"\n")
cat("R-squared =",round(summary(model)$r.squared,4),"\n")
