data(mtcars)
print(head(mtcars,10))
str(mtcars)
summary(mtcars)
dim(mtcars)
model<-lm(mpg~hp+wt+disp,data=mtcars)
print(summary(model))
print(coef(model))
print(summary(model)$coefficients)
new_car<-data.frame(hp=150,wt=3,disp=200)
prediction<-predict(model,new_car)
print(prediction)
actual<-mtcars$mpg
predicted<-predict(model)
rmse<-sqrt(mean((actual-predicted)^2))
mae<-mean(abs(actual-predicted))
r2<-summary(model)$r.squared
adj_r2<-summary(model)$adj.r.squared
cat("Predicted MPG =",round(prediction,2),"\n")
cat("RMSE =",round(rmse,2),"\n")
cat("MAE =",round(mae,2),"\n")
cat("R-squared =",round(r2,4),"\n")
cat("Adjusted R-squared =",round(adj_r2,4),"\n")
par(mfrow=c(2,2))
plot(model)
par(mfrow=c(1,1))
